const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const { test } = require('node:test');

const settingsSource = fs.readFileSync(path.join(__dirname, '../dist/settings.js'), 'utf8');
const header = 'SUPER MARIO KART SETTINGS. DO NOT EDIT THIS FILE.';
const bindings = [23, 25, 2, 71, 72, 73, 74, 36, 58, 36, 73, 74, 71, 72];

/** Keep real cfg parsing and filesystem I/O without opening native audio devices. */
function loadSettings({ appRoot, env = {}, platform = process.platform, home = '/home/player' }) {
    let music = 0.5;
    let sfx = 0.5;
    const keys = [...bindings];
    const errors = [];
    const Audio = {
        getMusicVolume: () => music,
        getSfxVolume: () => sfx,
        setVolume(musicValue, sfxValue) {
            music = musicValue;
            sfx = sfxValue;
        },
    };
    const Input = {
        get: action => keys[action],
        set: (action, code) => { keys[action] = code; },
    };
    const fixtureRoot = fs.realpathSync(path.dirname(appRoot));
    function assertFixturePath(filename) {
        const relative = path.relative(fixtureRoot, path.resolve(filename));
        assert.ok(
            relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative),
            `Settings test attempted a write outside its fixture: ${filename}`,
        );
    }
    const dependencies = {
        'node:fs': {
            ...fs,
            mkdirSync(filename, options) {
                assertFixturePath(filename);
                return fs.mkdirSync(filename, options);
            },
            writeFileSync(filename, contents, options) {
                assertFixturePath(filename);
                return fs.writeFileSync(filename, contents, options);
            },
        },
        'node:os': { homedir: () => home },
        'node:path': platform === 'win32' ? path.win32 : path.posix,
        'sfml.js': { VideoMode: { getDesktopMode: () => ({ size: { y: 2160 } }) } },
        './audio/audio': { Audio },
        './entities/enums': { BASIC_HEIGHT: 448 },
        './input/input': { Input, Key: { __COUNT: bindings.length } },
    };
    const context = {
        exports: {},
        __dirname: path.join(appRoot, 'dist'),
        process: { env, platform },
        console: { error: (...args) => errors.push(args) },
        require(id) {
            assert.ok(Object.hasOwn(dependencies, id), `Unexpected settings dependency: ${id}`);
            return dependencies[id];
        },
    };
    vm.runInNewContext(settingsSource, context, { filename: 'dist/settings.js' });
    return { Settings: context.exports.Settings, Audio, Input, errors };
}

/** Make only small config fixtures in OS temp; never copy the application. */
function fixture(t) {
    const directory = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'smk-settings-')));
    const previousCwd = process.cwd();
    t.after(() => {
        process.chdir(previousCwd);
        fs.rmSync(directory, { recursive: true, force: true });
    });
    // Legacy code writes to cwd even before a test can assert getFilePath().
    process.chdir(directory);
    const appRoot = path.join(directory, 'read only app');
    const configDir = path.join(directory, 'user config', 'nested');
    const filePath = path.join(configDir, 'smk_settings.cfg');
    const legacyPath = path.join(appRoot, 'smk_settings.cfg');
    fs.mkdirSync(appRoot);
    return {
        directory, appRoot, configDir, filePath, legacyPath,
        load: () => loadSettings({ appRoot, env: { SMK_CONFIG_DIR: configDir } }),
    };
}

/** Write a deliberately hand-specified cfg, including the original header line. */
function writeConfig(filePath, lines, newline = '\n') {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, [header, ...lines, ''].join(newline));
}

