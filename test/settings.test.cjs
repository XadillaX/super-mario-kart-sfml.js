test('creates and reloads writable settings outside the application directory', t => {
    const f = fixture(t);
    const { Settings, Audio, Input, errors } = f.load();
    assert.equal(Settings.getFilePath(), f.filePath);
    assert.equal(fs.existsSync(f.configDir), false, 'path lookup must not create directories');

    Settings.tryLoadSettings();
    assert.equal(fs.readFileSync(f.filePath, 'utf8'), [
        header, 'music_volume=50', 'sfx_volume=50', 'resolution=3',
        ...bindings.map((code, action) => `${action}=${code}`), '',
    ].join('\n'));
    Audio.setVolume(0.7, 0.35);
    Input.set(0, 42);
    Settings.decrementResolutionMultiplier();
    Settings.saveSettings();

    const reloaded = f.load();
    reloaded.Settings.tryLoadSettings();
    assert.ok(Math.abs(reloaded.Audio.getMusicVolume() - 0.7) < 1e-12);
    assert.ok(Math.abs(reloaded.Audio.getSfxVolume() - 0.35) < 1e-12);
    assert.equal(reloaded.Settings.getResolutionMultiplier(), 2);
    assert.equal(reloaded.Input.get(0), 42);
    assert.deepEqual(fs.readdirSync(f.appRoot), []);
    assert.deepEqual([...errors, ...reloaded.errors], []);
});

test('saveSettings creates the user directory even without a prior load', t => {
    const f = fixture(t);
    const { Settings, errors } = f.load();
    Settings.saveSettings();
    assert.equal(fs.existsSync(f.filePath), true);
    assert.deepEqual(fs.readdirSync(f.appRoot), []);
    assert.deepEqual(errors, []);
});

test('migrates an app-root cfg once, byte-for-byte, without changing the legacy file', t => {
    const f = fixture(t);
    writeConfig(f.legacyPath, ['music_volume=75', 'sfx_volume=20', 'resolution=6', '0=12'], '\r\n');
    const original = fs.readFileSync(f.legacyPath);
    const first = f.load();
    first.Settings.tryLoadSettings();
    assert.deepEqual(fs.readFileSync(f.filePath), original);
    assert.deepEqual(fs.readFileSync(f.legacyPath), original);
    assert.equal(first.Audio.getMusicVolume(), 0.75);
    assert.equal(first.Audio.getSfxVolume(), 0.2);
    assert.equal(first.Settings.getResolutionMultiplier(), 6);
    assert.equal(first.Input.get(0), 12);

    first.Audio.setVolume(0.4, 0.6);
    first.Settings.saveSettings();
    const saved = fs.readFileSync(f.filePath);
    writeConfig(f.legacyPath, ['music_volume=100', 'resolution=8']);
    const second = f.load();
    second.Settings.tryLoadSettings();
    assert.equal(second.Audio.getMusicVolume(), 0.4);
    assert.equal(second.Settings.getResolutionMultiplier(), 6);
    assert.deepEqual(fs.readFileSync(f.filePath), saved);
    assert.deepEqual([...first.errors, ...second.errors], []);
});

test('an existing user cfg wins over an app-root legacy cfg', t => {
    const f = fixture(t);
    writeConfig(f.legacyPath, ['music_volume=100', 'resolution=8']);
    writeConfig(f.filePath, ['music_volume=20', 'resolution=2']);
    const { Settings, Audio, errors } = f.load();
    Settings.tryLoadSettings();
    assert.equal(Audio.getMusicVolume(), 0.2);
    assert.equal(Settings.getResolutionMultiplier(), 2);
    assert.deepEqual(errors, []);
});

test('migration does not carry legacy read-only permissions into the user cfg', t => {
    const f = fixture(t);
    writeConfig(f.legacyPath, ['music_volume=75', 'resolution=4']);
    fs.chmodSync(f.legacyPath, 0o444);
    t.after(() => {
        if (fs.existsSync(f.legacyPath)) fs.chmodSync(f.legacyPath, 0o644);
    });
    const { Settings, Audio, errors } = f.load();
    Settings.tryLoadSettings();
    Audio.setVolume(0.2, 0.8);
    Settings.saveSettings();
    assert.match(fs.readFileSync(f.filePath, 'utf8'), /music_volume=20\nsfx_volume=80\n/);
    assert.match(fs.readFileSync(f.legacyPath, 'utf8'), /music_volume=75/);
    assert.deepEqual(errors, []);
});

test('ignores an unrelated cwd cfg when no app-root legacy cfg exists', t => {
    const f = fixture(t);
    const unrelatedPath = path.join(f.directory, 'smk_settings.cfg');
    writeConfig(unrelatedPath, ['music_volume=100', 'resolution=8']);
    const original = fs.readFileSync(unrelatedPath);
    const { Settings, Audio, errors } = f.load();
    Settings.tryLoadSettings();
    assert.equal(Audio.getMusicVolume(), 0.5);
    assert.equal(Settings.getResolutionMultiplier(), 3);
    assert.equal(fs.existsSync(f.filePath), true);
    assert.deepEqual(fs.readFileSync(unrelatedPath), original);
    assert.deepEqual(errors, []);
});

test('keeps original parseInt, CRLF, action-code and resolution-menu semantics', t => {
    const f = fixture(t);
    writeConfig(f.filePath, ['music_volume=65percent', 'sfx_volume=0', 'resolution=8', '13=-1'], '\r\n');
    const { Settings, Audio, Input, errors } = f.load();
    Settings.tryLoadSettings();
    assert.equal(Audio.getMusicVolume(), 0.65);
    assert.equal(Audio.getSfxVolume(), 0);
    assert.equal(Input.get(13), -1);
    assert.equal(Settings.incrementResolutionMultiplier(), false);
    assert.equal(Settings.decrementResolutionMultiplier(), true);
    assert.equal(Settings.getResolutionMultiplier(), 6);
    assert.deepEqual(errors, []);
});

for (const invalid of ['music_volume=23', 'sfx_volume=105', 'resolution=7', '14=1', 'unknown=5', 'broken']) {
    test(`invalid cfg entry ${invalid} retains parsed values and resets resolution`, t => {
        const f = fixture(t);
        writeConfig(f.filePath, ['music_volume=75', 'resolution=6', '0=12', invalid]);
        const { Settings, Audio, Input, errors } = f.load();
        Settings.tryLoadSettings();
        assert.equal(Settings.getResolutionMultiplier(), 3);
        assert.equal(Audio.getMusicVolume(), 0.75);
        assert.equal(Input.get(0), 12);
        assert.match(fs.readFileSync(f.filePath, 'utf8'), /resolution=3\n0=12\n/);
        assert.ok(errors.length > 0);
    });
}

test('an unwritable settings destination remains a reported, nonfatal save error', t => {
    const f = fixture(t);
    fs.mkdirSync(path.dirname(f.configDir));
    fs.writeFileSync(f.configDir, 'not a directory');
    const { Settings, errors } = f.load();
    assert.doesNotThrow(() => Settings.saveSettings());
    assert.ok(errors.length > 0);
    assert.deepEqual(fs.readdirSync(f.appRoot), []);
});
